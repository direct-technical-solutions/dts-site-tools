#!/usr/bin/env bash
# Tests whose downloaded plugins the tools read (SITE_PACKAGES_DIR in tools/site-packages.sh,
# template plan T28), run by the tools' self-check every time, on a stand-in repository holding
# its own site and a second site in a folder (as this site holds the starter). Without SITE_DIR the
# repository's list is read; with SITE_DIR the second site's, never the repository's, also when the
# second site has none (no silent borrowing). Each case loads the files in a fresh shell, since
# they set their paths once, read-only. Needs bash, jq and mktemp.
set -Euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
readonly HERE
readonly TOOLS_UNDER_TEST="$HERE/../../.."
WORK="$(mktemp -d)"
readonly WORK
trap 'rm -rf "$WORK"' EXIT

log() { printf '%s [site packages folder tests] %s\n' "$(date +%H:%M:%S)" "$*" >&2; }

# A lock file holding one WordPress plugin, named by its Composer name.
write_lock() {
  local folder="$1" package_name="$2"
  mkdir -p "$folder/site-packages"
  jq -n --arg name "$package_name" '{packages: [{name: $name, type: "wordpress-plugin"}]}' \
    >"$folder/site-packages/composer.lock"
}

write_stand_ins() {
  write_lock "$WORK/repository" "dts/repository-only-plugin"
  write_lock "$WORK/repository/second-site" "dts/second-site-plugin"
  mkdir -p "$WORK/repository/site-without-list"
}

# The plugins the tools read for one SITE_DIR ("" for none), in a fresh shell (read-plugins.sh).
plugins_read_with_site() {
  local site_dir="$1"
  env -u SITE_DIR ${site_dir:+SITE_DIR="$site_dir"} TOOLS_DIR="$TOOLS_UNDER_TEST" \
    PROJECT_DIR="$WORK/repository" bash "$HERE/read-plugins.sh"
}

expect_output() {
  local what="$1" expected="$2" actual="$3"
  [[ "$actual" == "$expected" ]] || { log "FAIL  $what: expected \"$expected\", got \"$actual\""; return 1; }
  log "ok    $what"
}

main() {
  local failed=0
  write_stand_ins
  expect_output "no SITE_DIR: the repository's list" "repository-only-plugin" \
    "$(plugins_read_with_site "")" || failed=1
  expect_output "a relative SITE_DIR: that site's list" "second-site-plugin" \
    "$(plugins_read_with_site second-site)" || failed=1
  expect_output "an absolute SITE_DIR: that site's list" "second-site-plugin" \
    "$(plugins_read_with_site "$WORK/repository/second-site")" || failed=1
  expect_output "a site without a list: none, not the repository's" \
    "no list at site-without-list/site-packages/composer.lock" \
    "$(plugins_read_with_site site-without-list)" || failed=1
  return "$failed"
}

main "$@"
