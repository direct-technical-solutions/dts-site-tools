#!/usr/bin/env bash
# Loads the tools' files as a command does (site-settings.sh, then site-packages.sh) and prints
# the plugins of the list they read, or "no list at <path>" when that list does not exist. Run by
# run.sh in a fresh shell per case, with TOOLS_DIR, PROJECT_DIR and, for some cases, SITE_DIR.
set -Euo pipefail

# shellcheck source=tools/site-settings.sh
source "$TOOLS_DIR/tools/site-settings.sh"
# shellcheck source=tools/site-packages.sh
source "$TOOLS_DIR/tools/site-packages.sh"

if [[ -f "$SITE_PACKAGES_LOCK" ]]; then
  site_packages_plugin_slugs "$SITE_PACKAGES_LOCK"
else
  printf 'no list at %s\n' "${SITE_PACKAGES_LOCK#"$PROJECT_DIR"/}"
fi
