#!/usr/bin/env bash
# Reading site-packages/, the downloaded plugins the site runs, pinned with Composer (template plan
# T8): composer.json lists them at exact versions, composer.lock records what was chosen, and
# bin/dev-site installs from the lock into site-packages/wp-content/ (ignored by git). Needs jq.
# Sourced, never run; the sourcing script defines TOOLS_DIR and PROJECT_DIR.

# shellcheck source=tools/plugin-header.sh
source "$TOOLS_DIR/tools/plugin-header.sh"

readonly SITE_PACKAGES_DIR="$PROJECT_DIR/site-packages"
readonly SITE_PACKAGES_LOCK="$SITE_PACKAGES_DIR/composer.lock"
readonly SITE_PACKAGES_PLUGINS_DIR="$SITE_PACKAGES_DIR/wp-content/plugins"
# WPackagist's name for WordPress.org's plugins: "wpackagist-plugin/<slug>".
readonly WORDPRESS_ORG_PLUGIN_VENDOR="wpackagist-plugin"
readonly FORM_PLUGIN_PACKAGE="$WORDPRESS_ORG_PLUGIN_VENDOR/contact-form-7"

# The WordPress plugins a lock file holds, as Composer names them ("vendor/slug").
site_packages_plugins() {
  local lock_file="$1"
  jq -r '.packages[] | select(.type == "wordpress-plugin") | .name' "$lock_file"
}

# The plugins' folder names, which are also their WordPress slugs.
site_packages_plugin_slugs() {
  local lock_file="$1"
  site_packages_plugins "$lock_file" | sed 's|^.*/||'
}

site_packages_wordpress_org_plugin_slugs() {
  local lock_file="$1"
  site_packages_plugins "$lock_file" | sed -n "s|^$WORDPRESS_ORG_PLUGIN_VENDOR/||p"
}

# DTS's own plugins (template plan T25): Composer's "dts/<slug>", each released by a Git tag in its
# own public repository, "dts-<slug>" in DTS's GitHub organization.
readonly DTS_PLUGIN_VENDOR="dts"
readonly DTS_GITHUB_OWNER="direct-technical-solutions"
site_packages_dts_plugin_slugs() {
  local lock_file="$1"
  site_packages_plugins "$lock_file" | sed -n "s|^$DTS_PLUGIN_VENDOR/||p"
}

# Prints a line for each plugin bin/dev-site and bin/deploy cannot install, starting with its name:
# anything but WordPress.org's plugins (checked against WordPress.org's checksums) and DTS's own
# (checked by their release commit, site_packages_download_problems). Two plugins sharing one
# folder name are named by that folder: both would be copied into it.
site_packages_unsupported_plugins() {
  local lock_file="$1" package
  while IFS= read -r package; do
    [[ "$package" == "$WORDPRESS_ORG_PLUGIN_VENDOR/"* || "$package" == "$DTS_PLUGIN_VENDOR/"* ]] ||
      printf "%s: neither WordPress.org's nor one of DTS's plugins; the tools cannot install it\n" "$package"
  done < <(site_packages_plugins "$lock_file")
  jq -r '[.packages[] | select(.type == "wordpress-plugin") | .name]
    | group_by(sub("^.*/"; "")) | map(select(length > 1))[]
    | "\(.[0] | sub("^.*/"; "")): one folder for \(length) plugins (\(join(", ")))"' "$lock_file"
}

# Prints a line for each downloaded plugin whose download the tools do not trust, starting with its
# name; nothing when every one is trusted. The lock file's addresses come from WPackagist, a third
# party (template plan T8), and from DTS's repositories, so each is held to its one trusted form.
site_packages_download_problems() {
  local lock_file="$1"
  site_packages_wordpress_org_download_problems "$lock_file"
  site_packages_dts_download_problems "$lock_file"
}

# A WordPress.org plugin must download from WordPress.org's own server, where its checksums are.
readonly WORDPRESS_ORG_DOWNLOADS="https://downloads.wordpress.org/plugin/"
site_packages_wordpress_org_download_problems() {
  local lock_file="$1"
  jq -r --arg vendor "$WORDPRESS_ORG_PLUGIN_VENDOR/" --arg server "$WORDPRESS_ORG_DOWNLOADS" '
    .packages[] | select(.name | startswith($vendor))
    | select((.dist.url // "") | startswith($server) | not)
    | "\(.name): downloads from \(.dist.url // "(no address)"), not \($server)"' "$lock_file"
}

# A DTS plugin must come from its own repository in DTS's organization, its download being GitHub's
# archive of exactly the commit the lock records (template plan T25, D1). GitHub publishes no
# checksum for its archives and Composer records none (an empty "shasum"), so the commit, which
# names the files, is what ties the download to the release; GitHub is trusted for it, as it is for
# the tools themselves.
site_packages_dts_download_problems() {
  local lock_file="$1"
  jq -r --arg vendor "$DTS_PLUGIN_VENDOR/" --arg owner "$DTS_GITHUB_OWNER" '
    .packages[] | select(.name | startswith($vendor))
    | (.name | sub("^[^/]*/"; "dts-")) as $repository
    | (.source.reference // "") as $commit
    | if ($commit | test("^[0-9a-f]{40}$") | not) then "\(.name): no release commit in the lock file (source.reference \"\($commit)\")"
      elif .source.type != "git" or .source.url != "https://github.com/\($owner)/\($repository).git" then
        "\(.name): its source is \(.source.url // "(no address)"), not https://github.com/\($owner)/\($repository).git"
      elif .dist.url != "https://api.github.com/repos/\($owner)/\($repository)/zipball/\($commit)" or .dist.reference != $commit then
        "\(.name): downloads \(.dist.url // "(no address)"), not https://api.github.com/repos/\($owner)/\($repository)/zipball/\($commit), the release commit"
      else empty end' "$lock_file"
}

# The release commit the lock file records for a DTS plugin, by its slug.
site_packages_release_commit() {
  local lock_file="$1" plugin_slug="$2"
  jq -r --arg name "$DTS_PLUGIN_VENDOR/$plugin_slug" '.packages[] | select(.name == $name) | .source.reference' "$lock_file"
}

# The packages whose installed code differs between two lock files (added, removed, or another
# version, download or source), one name a line. Bookkeeping fields are left out: Dependabot's own
# Composer writes some differently (it drops "published-time") without changing what is installed.
site_packages_changed_packages() {
  local base_lock="$1" head_lock="$2"
  jq -rn --slurpfile base "$base_lock" --slurpfile head "$head_lock" '
    def installed: map({key: .name, value: {version, dist, source}}) | from_entries;
    ($base[0].packages | installed) as $before
    | ($head[0].packages | installed) as $after
    | [$before, $after] | map(keys[]) | unique[] | select($before[.] != $after[.])'
}

# Prints a line for each changed package that is not a WordPress.org plugin, starting with its
# name, and one line when nothing changed; nothing when only WordPress.org plugins changed. Only
# such a change may merge itself (template plan T9): a WordPress.org plugin is checked against
# WordPress.org's checksums, while anything else (composer/installers runs code as Composer
# installs) waits for the user's review.
site_packages_not_plugins_only() {
  local base_lock="$1" head_lock="$2" changed package
  changed="$(site_packages_changed_packages "$base_lock" "$head_lock")"
  if [[ -z "$changed" ]]; then
    printf 'composer.lock: no package changed\n'
    return 0
  fi
  while IFS= read -r package; do
    [[ "$package" == "$WORDPRESS_ORG_PLUGIN_VENDOR/"* ]] || printf '%s: changed, and not a WordPress.org plugin\n' "$package"
  done <<<"$changed"
}

# Prints a line, starting with the form plugin's name, when the site has the booking form's files
# but its lock file does not hold the form's plugin; nothing otherwise.
site_packages_booking_form_problem() {
  local form_file="$1" lock_file="$2"
  [[ -f "$form_file" ]] || return 0
  site_packages_plugins "$lock_file" | grep -qxF "$FORM_PLUGIN_PACKAGE" && return 0
  printf "%s: the booking form's files exist, but site-packages/composer.json does not require it\n" "$FORM_PLUGIN_PACKAGE"
}

# A downloaded plugin's version as a lock file pins it, by its slug, as the plugin's own header
# writes it: a DTS plugin's tag "v1.2.0" is version 1.2.0. Nothing when it is not there. One slug
# names one plugin (site_packages_unsupported_plugins refuses two).
site_packages_pinned_version() {
  local lock_file="$1" plugin_slug="$2"
  jq -r --arg slug "$plugin_slug" '.packages[]
    | select(.type == "wordpress-plugin" and (.name | sub("^.*/"; "")) == $slug) | .version | sub("^v"; "")' "$lock_file"
}

# WordPress.org's checksum file for a plugin's release: every file's SHA-256, by its path.
readonly WORDPRESS_ORG_CHECKSUMS="https://downloads.wordpress.org/plugin-checksums"
site_packages_checksums_address() {
  local plugin_slug="$1" version="$2"
  printf '%s/%s/%s.json' "$WORDPRESS_ORG_CHECKSUMS" "$plugin_slug" "$version"
}

# Prints a line for each file of a built plugin folder that WordPress.org's checksum file does not
# vouch for, starting with the file's path: missing, different, or not in the release at all;
# nothing when every file matches and none is missing (seen exact on 2026-11-21 for Contact Form 7
# and Yoast SEO). A file may list several SHA-256 values, any of which counts. Fails when the
# checksum file is not WordPress.org's shape, so a broken answer is never read as "no files".
site_packages_checksum_problems() {
  local plugin_dir="$1" checksums_file="$2" expected actual
  expected="$(jq -er '.files | to_entries[] | .key as $path | (.value.sha256 | if type == "array" then .[] else . end) | "\($path)\t\(.)"' "$checksums_file" 2>/dev/null)" ||
    { printf '%s: not a WordPress.org checksum file\n' "$checksums_file"; return 1; }
  actual="$(cd "$plugin_dir" && find . -type f -printf '%P\n' | sort | while IFS= read -r path; do
    printf '%s\t%s\n' "$path" "$(sha256sum "$path" | cut -d' ' -f1)"
  done)"
  awk -F'\t' '
    FNR == NR { allowed[$1 "\t" $2] = 1; listed[$1] = 1; next }
    { present[$1] = 1
      if (!($1 in listed)) print $1 ": not in the release"
      else if (!(($1 "\t" $2) in allowed)) print $1 ": differs from the release" }
    END { for (path in listed) if (!(path in present)) print path ": missing" }' \
    <(printf '%s\n' "$expected") <(printf '%s\n' "$actual") | sort
}

# Prints a line, starting with the plugin's slug, when a built plugin folder's main file names
# another version than the lock file pins, or none; nothing when they agree. For a DTS plugin this
# shows that the download is the release the pin names (its release check holds the tag and the
# header equal, template plan T25), and bin/deploy's "never lower" check reads that header.
site_packages_header_version_problem() {
  local lock_file="$1" plugin_dir="$2" plugin_slug="$3" main_file pinned header
  pinned="$(site_packages_pinned_version "$lock_file" "$plugin_slug")"
  main_file="$(plugin_main_file "$plugin_dir")" || { printf '%s: no main plugin file in the download\n' "$plugin_slug"; return 0; }
  header="$(plugin_header_version "$plugin_dir/$main_file")"
  [[ "$header" == "$pinned" ]] || printf '%s: the download says version %s, the pin %s\n' "$plugin_slug" "${header:-(none)}" "$pinned"
}

# Prints a line, starting with the slug, for each rule of shared code a downloaded DTS plugin
# breaks; nothing when it keeps them. It is shared by every site that uses it, so it must name
# nothing of this one (site_settings_names_in, with the site's settings file); its own repository
# cannot check that without a public list of every site's names, so each site checks the release
# it installs against its own (template plan T20, T26). Its header must also keep WordPress.org
# from offering a plugin of the same name as an update. Needs tools/site-settings.sh.
site_packages_dts_shared_code_problems() {
  local settings_file="$1" plugin_dir="$2" plugin_slug="$3" found
  found="$(site_settings_names_in "$settings_file" "$plugin_dir")"
  [[ -z "$found" ]] ||
    printf '%s: names the site (its namesSharedCodeMustNotUse) in %s\n' "$plugin_slug" \
      "$(cut -d: -f1-2 <<<"${found//"$plugin_dir"\//}" | paste -sd ' ')"
  plugin_never_updated_from_wordpress_org "$plugin_dir/$plugin_slug.php" ||
    printf '%s: %s.php has no "Update URI: false" header\n' "$plugin_slug" "$plugin_slug"
  return 0
}

# Prints a line, starting with the slug, for each of the site's own plugins (site.json's
# localPlugins, given after the lock file) that is also a downloaded plugin: both would be put into
# the same folder, on the dev site and on the server. Nothing otherwise.
site_packages_local_plugin_clashes() {
  local lock_file="$1" local_slug
  shift
  for local_slug in "$@"; do
    # grep reads every line (no -q): stopping early could end sed with an error, which pipefail
    # would count as no clash.
    site_packages_plugin_slugs "$lock_file" | grep -xF -- "$local_slug" >/dev/null &&
      printf '%s: in localPlugins and downloaded too (site-packages/composer.lock); list it in one only\n' "$local_slug"
  done
  return 0
}

# Succeeds when version $1 is lower than version $2 (as sort -V orders release numbers).
version_is_lower() {
  local lower="$1" higher="$2"
  [[ "$lower" != "$higher" && "$(printf '%s\n%s\n' "$lower" "$higher" | sort -V | head -n 1)" == "$lower" ]]
}
